package sh.edm.s1kiosk

import android.app.Application
import android.content.Context
import android.util.Log
import org.mozilla.geckoview.GeckoResult
import org.mozilla.geckoview.GeckoRuntime
import org.mozilla.geckoview.GeckoRuntimeSettings
import org.mozilla.geckoview.WebExtension
import java.io.File

class KioskApp : Application() {

    companion object {
        private const val TAG = "S1Kiosk"
        private var runtime: GeckoRuntime? = null

        /** `dom.securecontext.allowlist` hosts written at startup (changing them needs a restart). */
        @Volatile var startupSecureHosts: List<String> = emptyList()
            private set

        /**
         * One GeckoRuntime per process. Gecko prefs are injected through a YAML config file,
         * which GeckoView reads once at startup; changing them requires a process restart.
         */
        fun runtime(context: Context): GeckoRuntime {
            runtime?.let { return it }
            val app = context.applicationContext
            val prefs = KioskPrefs(app)
            val config = writeGeckoConfig(app, prefs)
            val settings = GeckoRuntimeSettings.Builder()
                .configFilePath(config.absolutePath)
                .consoleOutput(true)
                .aboutConfigEnabled(true)
                .remoteDebuggingEnabled(prefs.remoteDebugging)
                .build()
            return GeckoRuntime.create(app, settings).also { runtime = it }
        }

        private var helper: GeckoResult<WebExtension>? = null

        /** Built-in helper extension (assets/extension): HA kiosk tweaks + page<->app messaging. */
        fun helperExtension(context: Context): GeckoResult<WebExtension> {
            helper?.let { return it }
            return runtime(context).webExtensionController
                .ensureBuiltIn("resource://android/assets/extension/", "helper@s1kiosk.edm.sh")
                .also { helper = it }
        }

        private fun writeGeckoConfig(context: Context, prefs: KioskPrefs): File {
            startupSecureHosts = prefs.secureHosts()
            val hosts = startupSecureHosts.joinToString(",")
            val p = linkedMapOf<String, Any>(
                // HA is usually plain http on the LAN. Treat its host as a secure context so
                // navigator.mediaDevices / getUserMedia / AudioWorklet are exposed.
                "dom.securecontext.allowlist" to hosts,
                // Belt and braces for the same thing via the legacy insecure-media prefs.
                "media.devices.insecure.enabled" to true,
                "media.getusermedia.insecure.enabled" to true,
                // Kiosk: no prompts (the PermissionDelegate grants too), autoplay allowed.
                "media.navigator.permission.disabled" to true,
                "media.autoplay.default" to 0,
                "media.autoplay.blocking_policy" to 0,
                "media.autoplay.block-webaudio" to false,
                // Kiosk niceties.
                "browser.tabs.warnOnClose" to false,
                "dom.disable_beforeunload" to true,
            )
            if (prefs.zoom > 0f) p["layout.css.devPixelsPerPx"] = prefs.zoom.toString()

            val yaml = buildString {
                appendLine("# Generated by S1 Kiosk at startup; edits are overwritten.")
                appendLine("prefs:")
                for ((k, v) in p) {
                    val value = when (v) {
                        is String -> "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
                        else -> v.toString()
                    }
                    appendLine("  $k: $value")
                }
            }
            val f = File(context.filesDir, "geckoview-config.yaml")
            f.writeText(yaml)
            Log.i(TAG, "Gecko config:\n$yaml")
            return f
        }
    }
}
