// bootpatch: unit tests + byte-exact comparisons against goldens made by the real CLI
// (tools/root/patch-boot-magisk.sh in Docker, tools/branding/set-bootlogo.py).
//
// The goldens contain Aqara's boot images and Magisk binaries, so they live outside the repo:
//   S1_WEB_GOLDEN=~/src/aqara-panel-backups/web-golden npm test
// (that path is also the default). Without them the golden tests are skipped; the unit tests run.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';

import { parseBootImage } from '../src/bootpatch/bootimg';
import { type Compressor, loadCompressor } from '../src/bootpatch/compress';
import { Cpio, S_IFDIR, S_IFREG, patchEncryption, patchVerity } from '../src/bootpatch/cpio';
import { crc32, grepProp, magiskConfigText } from '../src/bootpatch/magisk';
import {
  type OverlayFile, isMagiskPatched, patchBoot, replaceBootlogo, s1Overlay, vbmetaFlags, withVbmetaFlags,
} from '../src/bootpatch/index';

const GOLDEN = process.env.S1_WEB_GOLDEN ?? join(homedir(), 'src/aqara-panel-backups/web-golden');
const HAVE_GOLDEN = existsSync(join(GOLDEN, 'out/SHA256SUMS'));
const SKIP_MSG = `[bootpatch] golden tests SKIPPED: no goldens at ${GOLDEN} (set S1_WEB_GOLDEN; they are ` +
  `generated by gen.sh in that directory and are never committed)`;

const enc = new TextEncoder();
const g = (p: string) => new Uint8Array(readFileSync(join(GOLDEN, p)));
const sha256 = (d: Uint8Array) => createHash('sha256').update(d).digest('hex');

/** Equal bytes, reported by hash + first differing offset instead of a 32 MiB diff. */
function expectSameBytes(got: Uint8Array, want: Uint8Array, what: string) {
  if (got.length === want.length && Buffer.compare(got, want) === 0) return;
  let i = 0;
  while (i < got.length && i < want.length && got[i] === want[i]) i++;
  expect.fail(`${what}: differs (len ${got.length} vs ${want.length}, first diff @0x${i.toString(16)}; ` +
    `sha256 ${sha256(got)} vs ${sha256(want)})`);
}

let comp: Compressor;
beforeAll(async () => { comp = await loadCompressor(); });

it.runIf(!HAVE_GOLDEN)('golden fixtures are absent: golden tests skipped', () => { process.stderr.write(SKIP_MSG + '\n'); });

