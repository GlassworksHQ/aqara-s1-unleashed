#!/usr/bin/env node
// Copies the Glassworks brand into Kiln from glassworks.dev at the commit in source.json, so Kiln and
// the site read the same tokens and drawings and nobody copies a colour by hand (#32).
//
//   node sync.mjs            write src/ from GitHub (or from GLASSWORKS_DEV=<a local checkout>)
//   node sync.mjs --check    exit 1 if src/ differs from what that commit gives
//
// To take a newer brand: change `ref` in source.json, run it, and commit both. Reads the network or a
// local checkout; writes only src/ in this folder.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const { repo, ref } = JSON.parse(readFileSync(join(here, 'source.json'), 'utf8'));
const local = process.env.GLASSWORKS_DEV;

async function read(path) {
  if (local) return readFileSync(join(local, path), 'utf8');
  const r = await fetch(`https://raw.githubusercontent.com/${repo}/${ref}/${path}`);
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`);
  return r.text();
}

const from = (path) => `${repo}@${ref.slice(0, 7)} ${path}`;
const header = (path) => `/* Generated by kiln/packages/brand/sync.mjs from ${from(path)}. Don't edit; run the script. */\n`;

/** The token blocks of the site's globals.css: `:root { … }` and its dark-mode override, nothing else. */
function tokens(css) {
  const start = css.indexOf(':root {');
  const dark = css.indexOf('@media (prefers-color-scheme: dark)', start);
  const end = css.indexOf('\n}\n', css.indexOf('\n  }\n', dark)) + 3;
  if (start < 0 || dark < 0 || end < 3) throw new Error('globals.css: token blocks not found');
  return css.slice(start, end);
}

const files = {
  'src/tokens.css': async () => header('src/app/globals.css') + tokens(await read('src/app/globals.css')),
  'src/mark.ts': async () => `// Generated by kiln/packages/brand/sync.mjs from ${from('src/lib/markGeometry.ts')}. Don't edit; run the script.\n`
    + '// @ts-nocheck: written for the site\'s compiler options, not Kiln\'s stricter noUncheckedIndexedAccess.\n'
    + await read('src/lib/markGeometry.ts'),
  'src/icon-kiln.svg': () => read('public/brand/icon-kiln-on-dark.svg'),
};

let differs = 0;
for (const [out, make] of Object.entries(files)) {
  const want = await make();
  const path = join(here, out);
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (have !== want) { console.error(`${out} differs from ${from('')}`); differs++; }
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${out}`);
  }
}
if (differs) process.exit(1);
